def export_benchmark_markdown(suite: BenchmarkSuiteResult) -> str:
    """Formats benchmark evaluation results as a Markdown audit report."""
    now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    lines = [
        "# DocuMind AI — RAG Evaluation & Benchmark Audit Report",
        "",
        f"**Generated**: {now_iso}  ",
        f"**Evaluated Provider**: {suite.provider}  ",
        f"**Retrieval Mode**: {suite.retrieval_mode.upper()} (Top-K: {suite.top_k})  ",
        "",
        "---",
        "",
        "## Summary Metrics",
        f"- **Total Benchmark Cases**: {suite.total_cases}",
        f"- **Passed Cases**: {suite.passed_cases} ({round(suite.passed_cases / max(1, suite.total_cases) * 100, 1)}%)",
        f"- **Failed Cases**: {suite.failed_cases}",
        f"- **Overall Hit Rate @ 3**: {suite.overall_hit_rate_at_3 * 100:.1f}%",
        f"- **Mean Reciprocal Rank (MRR)**: {suite.overall_mrr:.4f}",
        f"- **Mean Precision @ {suite.top_k}**: {suite.overall_precision * 100:.1f}%",
        f"- **Mean Recall @ {suite.top_k}**: {suite.overall_recall * 100:.1f}%",
        f"- **Citation Grounding Precision**: {suite.overall_citation_precision * 100:.1f}%",
        f"- **Factual Grounding Accuracy**: {suite.grounding_accuracy * 100:.1f}%",
        f"- **Average Query Latency**: {suite.avg_latency_seconds:.3f} s",
        "",
        "---",
        "",
        "## Detailed Per-Case Evaluation Audit",
        "",
        "| ID | Category | Status | Hit@3 | MRR | Cit. Prec. | Latency | Question |",
        "|---|---|---|---|---|---|---|---|",
    ]

    for c in suite.case_results:
        status_icon = "✓ PASS" if c.status == "PASS" else "❌ FAIL"
        lines.append(
            f"| `{c.case_id}` | {c.category} | {status_icon} | {c.hit_at_3:.1f} | {c.mrr:.2f} | {c.citation_precision:.2f} | {c.latency_seconds}s | {c.question[:45]}... |"
        )

    lines.extend([
        "",
        "---",
        "*Report generated by DocuMind AI · Created by Abhishek Chaudhary*",
    ])
    return "\n".join(lines)
