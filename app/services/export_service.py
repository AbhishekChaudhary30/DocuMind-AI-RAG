def sanitize_filename(name: str) -> str:
    """Sanitizes filename strings removing illegal filesystem characters."""
    clean = re.sub(r'[\\/*?:"<>| ]+', "_", name)
    return clean[:64].strip("_") or "documind_export"


def export_answer_markdown(
    question: str,
    answer: str,
    citations: List[Citation],
    retrieved_results: List[RetrievalResult],
    provider: str,
    model: str,
    retrieval_mode: str,
    latency_seconds: float,
) -> str:
    """Formats a Q&A interaction and its verified evidence citations as Markdown."""
    now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    lines = [
        "# DocuMind AI — Q&A Evidence Report",
        "",
        f"**Generated**: {now_iso}  ",
        f"**Inference Engine**: {provider} ({model})  ",
        f"**Retrieval Strategy**: {retrieval_mode.upper()}  ",
        f"**Turnaround Latency**: {latency_seconds}s  ",
        "",
        "---",
        "",
        "## User Question",
        f"> {question}",
        "",
        "## Synthesized Answer",
        answer,
        "",
        "---",
        "",
        "## Verified Source Citations",
    ]

    if citations:
        for idx, c in enumerate(citations):
            status = "Verified" if c.is_valid else "Unverified / Flagged"
            lines.append(f"### {c.source_label or f'[Source {idx+1}]'} — {c.filename}")
            lines.append(f"- **Page**: {c.page_range or f'Page {c.page_number}'}")
            lines.append(f"- **Status**: {status}")
            lines.append(f"- **Relevance Score**: {c.relevance_score}")
            lines.append(f"- **Supporting Evidence Excerpt**:\n  > \"{c.snippet}\"")
            lines.append("")
    else:
        lines.append("*No citations were associated with this response.*")
        lines.append("")

    lines.extend([
        "---",
        "",
        f"*Report generated by DocuMind AI · Created by Abhishek Chaudhary*",
    ])
    return "\n".join(lines)


def export_answer_json(
    question: str,
    answer: str,
    citations: List[Citation],
    retrieved_results: List[RetrievalResult],
    provider: str,
    model: str,
    retrieval_mode: str,
    latency_seconds: float,
) -> str:
    """Serializes a Q&A interaction to structured JSON with zero credential exposure."""
    data = {
        "report_type": "qa_evidence_report",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "query": question,
        "answer": answer,
        "pipeline_configuration": {
            "provider": provider,
            "model": model,
            "retrieval_mode": retrieval_mode,
            "latency_seconds": latency_seconds,
        },
        "citations": [
            {
                "citation_id": c.citation_id,
                "source_label": c.source_label,
                "filename": c.filename,
                "page_number": c.page_number,
                "page_range": c.page_range,
                "snippet": c.snippet,
                "relevance_score": c.relevance_score,
                "is_valid": c.is_valid,
                "verification_status": c.verification_status,
            }
            for c in citations
        ],
        "candidate_passages_retrieved": [
            {
                "rank": r.rank,
                "score": r.score,
                "filename": r.chunk.filename,
                "start_page": r.chunk.start_page,
                "end_page": r.chunk.end_page,
                "excerpt": r.chunk.text[:250],
            }
            for r in retrieved_results
        ],
    }
    return json.dumps(data, indent=2)


def export_analysis_markdown(analysis: AnalysisResult) -> str:
    """Formats corpus intelligence analysis findings as a structured Markdown document."""
    now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    docs_str = ", ".join(analysis.document_titles) if analysis.document_titles else "Corpus"

    lines = [
        f"# DocuMind AI — Document Intelligence Report: {docs_str}",
        "",
        f"**Generated**: {now_iso}  ",
        f"**Analyzed Documents**: {len(analysis.document_titles)}  ",
        "",
        "---",
        "",
        "## 1. Corpus Structural Telemetry",
    ]

    for k, v in analysis.structural_stats.items():
        lines.append(f"- **{k}**: {v}")

    lines.extend([
        "",
        "## 2. Executive Summary",
        analysis.summary,
        "",
        "## 3. Key Thematic Topics",
    ])

    for topic in analysis.key_topics:
        lines.append(f"- `{topic}`")

    if analysis.key_entities:
        lines.extend(["", "## 4. Extracted Domain Entities"])
        for cat, items in analysis.key_entities.items():
            lines.append(f"### {cat}")
            for item in items:
                lines.append(f"- {item}")

    if analysis.important_facts:
        lines.extend(["", "## 5. Critical Factual Assertions"])
        for fact in analysis.important_facts:
            lines.append(f"- {fact}")

    if analysis.suggested_questions:
        lines.extend(["", "## 6. Recommended Exploratory Queries"])
        for q in analysis.suggested_questions:
            lines.append(f"- 💡 {q}")

    lines.extend([
        "",
        "---",
        "*Report generated by DocuMind AI · Created by Abhishek Chaudhary*",
    ])
    return "\n".join(lines)


