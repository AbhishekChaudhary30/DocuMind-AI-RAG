def export_benchmark_csv(suite: BenchmarkSuiteResult) -> str:
    """Exports per-case benchmark evaluation results to CSV format."""
    output = io.StringIO()
    writer = csv.writer(output)

    # Header
    writer.writerow([
        "Case ID",
        "Category",
        "Status",
        "Question",
        "Expected Document",
        "Expected Pages",
        "Retrieved Document",
        "Retrieved Pages",
        "Hit@3",
        "MRR",
        "Precision@K",
        "Recall@K",
        "Citation Precision",
        "Grounding Passed",
        "Keyword Coverage",
        "Latency (s)",
    ])

    for c in suite.case_results:
        writer.writerow([
            c.case_id,
            c.category,
            c.status,
            c.question,
            c.expected_doc,
            ";".join(str(p) for p in c.expected_pages),
            c.retrieved_doc,
            ";".join(str(p) for p in c.retrieved_pages),
            c.hit_at_3,
            c.mrr,
            c.precision_at_k,
            c.recall_at_k,
            c.citation_precision,
            c.grounding_passed,
            c.keyword_coverage,
            c.latency_seconds,
        ])

    return output.getvalue()


