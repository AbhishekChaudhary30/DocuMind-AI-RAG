"""Deterministic citation extraction, source validation, and grounding verification."""

import re
from typing import Dict, List, Set, Tuple
from app.models.schemas import Citation, DocumentChunk, RetrievalResult


def parse_and_validate_citations(
    answer_text: str,
    source_registry: Dict[str, DocumentChunk],
    retrieved_results: List[RetrievalResult],
) -> List[Citation]:
    """Extracts citation markers from answer text and verifies them against the request source registry."""
    if not answer_text:
        return []

    # Patterns matching: [Source 1], [Source: 1], [Source 1, Page 2], [1]
    citation_patterns = [
        re.compile(r"\[Source\s*[:\-]?\s*(\d+)\]", re.IGNORECASE),
        re.compile(r"\[(\d+)\]"),
    ]

    cited_ids: Set[str] = set()
    for pattern in citation_patterns:
        for match in pattern.finditer(answer_text):
            cited_ids.add(match.group(1).strip())

    citations: List[Citation] = []
    seen_chunk_ids: Set[str] = set()

    for num_str in sorted(cited_ids, key=lambda x: int(x) if x.isdigit() else 999):
        lookup_key = num_str.lower()
        chunk = source_registry.get(lookup_key)

        if chunk is not None:
            if chunk.chunk_id in seen_chunk_ids:
                continue
            seen_chunk_ids.add(chunk.chunk_id)

            # Extract leading excerpt as supporting snippet
            snippet = chunk.text.strip()[:240] + ("..." if len(chunk.text.strip()) > 240 else "")
            page_range = f"p. {chunk.start_page}" if chunk.start_page == chunk.end_page else f"pp. {chunk.start_page}-{chunk.end_page}"

            # Look up relevance score from retrieved_results
            rel_score = 0.85
            for r in retrieved_results:
                if r.chunk.chunk_id == chunk.chunk_id:
                    rel_score = r.score
                    break

            cit = Citation(
                citation_id=f"cit_{chunk.chunk_id}",
                chunk_id=chunk.chunk_id,
                doc_id=chunk.doc_id,
                filename=chunk.filename,
                page_number=chunk.start_page,
                page_range=page_range,
                snippet=snippet,
                relevance_score=rel_score,
                source_label=f"[Source {num_str}]",
                verification_status="verified",
                is_valid=True,
            )
            citations.append(cit)
        else:
            # Phantom or out-of-bounds citation hallucinated by model
            cit = Citation(
                citation_id=f"cit_invalid_{num_str}",
                chunk_id=f"unknown_chunk_{num_str}",
                doc_id="unknown_doc",
                filename="Unknown Source",
                page_number=1,
                snippet="Citation was generated by model but does not correspond to supplied context.",
                relevance_score=0.0,
                source_label=f"[Source {num_str}]",
                verification_status="invalid_source",
                is_valid=False,
            )
            citations.append(cit)

    # Deterministic fallback: If the model omitted inline citations entirely and did not abstain,
    # associate the top retrieved chunks as supporting evidence without false sentence-level claims
    abstention_cues = ["insufficient", "cannot answer", "not provide", "not contain", "unsupported", "do not contain"]
    is_abstaining = any(cue in answer_text.lower() for cue in abstention_cues)

    if not citations and retrieved_results and not is_abstaining:
        for idx, res in enumerate(retrieved_results[:3]):
            chunk = res.chunk
            snippet = chunk.text.strip()[:240] + ("..." if len(chunk.text.strip()) > 240 else "")
            page_range = f"p. {chunk.start_page}" if chunk.start_page == chunk.end_page else f"pp. {chunk.start_page}-{chunk.end_page}"

            citations.append(
                Citation(
                    citation_id=f"cit_evidence_{chunk.chunk_id}",
                    chunk_id=chunk.chunk_id,
                    doc_id=chunk.doc_id,
                    filename=chunk.filename,
                    page_number=chunk.start_page,
                    page_range=page_range,
                    snippet=snippet,
                    relevance_score=res.score,
                    source_label=f"[Source {idx + 1}]",
                    verification_status="retrieved_evidence",
                    is_valid=True,
                )
            )

    return citations
